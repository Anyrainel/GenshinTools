import { readFile, writeFile } from "node:fs/promises";
import {
  ELEMENT_BACKGROUND,
  ELEMENT_HEX,
  ITEM_TOKENS,
  RARITY_GRADIENTS,
  RARITY_TOKENS,
  TIER_TOKENS,
} from "../src/config/gameColors.ts";

const target = new URL("../src/generated/game-palette.css", import.meta.url);
const declarations = [];
function color(name, value) {
  declarations.push(`  --color-${name}: ${value};`);
}
for (const [element, value] of Object.entries(ELEMENT_HEX)) {
  color(`element-${element.toLowerCase()}`, value);
}
color("element-bg", ELEMENT_BACKGROUND);
for (const [tier, value] of Object.entries(TIER_TOKENS)) {
  color(`tier-${tier}`, value);
}
for (const [rarity, value] of Object.entries(RARITY_TOKENS)) {
  color(`rarity-${rarity}`, value);
}
for (const [id, value] of Object.entries(ITEM_TOKENS)) {
  if (typeof value === "string") {
    color(`item-${id}`, value);
  } else {
    color(`item-${id}`, value.DEFAULT);
    color(`item-${id}-foreground`, value.foreground);
  }
}
const gradients = Object.entries(RARITY_GRADIENTS).map(
  ([name, value]) => `@utility bg-${name} {\n  background-image: ${value};\n}`
);
const css = `/* Generated by scripts/generate-game-palette.mjs; edit src/config/gameColors.ts. */\n@theme inline {\n${declarations.join("\n")}\n}\n\n${gradients.join("\n\n")}\n`;
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== css) {
    throw new Error("Game palette CSS drifted; run npm run styles:generate.");
  }
} else {
  await writeFile(target, css);
}
